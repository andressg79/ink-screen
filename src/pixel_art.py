# String name mapping to ID
SPRITE_NAMES = {
    "caballero": 1,
    "brujo": 2,
    "bruja": 3,
    "nigromante": 4,
    "elfo": 5,
    "ogro": 6,
    "enano": 7,
    "enano minero": 7,  # Aliases
    "doncella": 8,
    "paisano": 9
}

def get_pixel_art_image(character_id_or_name) -> Image.Image:
    """
    Generates a 64x64 monochrome PIL Image representing the character.
    Uses 2x2 ordered dithering pattern to render 4 shades of gray.
    Accepts character ID (int 1-9) or character name (str).
    Defaults to the slime/paisano (ID 9) if not found.
    """
    # 1. Resolve character_id
    sprite_id = 9  # default paisano
    
    if isinstance(character_id_or_name, str):
        name_clean = character_id_or_name.lower().strip()
        sprite_id = SPRITE_NAMES.get(name_clean, 9)
    elif isinstance(character_id_or_name, int):
        if character_id_or_name in SPRITES:
            sprite_id = character_id_or_name
        else:
            logger.warning(f"ID de pixel art {character_id_or_name} no existe. Usando paisano (9).")
    else:
        logger.warning(f"Tipo de ID de pixel art no reconocido ({type(character_id_or_name)}). Usando paisano (9).")

    sprite_data = SPRITES.get(sprite_id, SPRITES[9])

    # 2. Render 64x64 monochrome image using 2x2 ordered dithering
    # 2x2 patterns map level 0-3 to 1-bit monochrome pixels
    # 0 (White): all 255
    # 1 (Light Gray): 1 black pixel out of 4 (upper left)
    # 2 (Dark Gray): 2 black pixels out of 4 (diagonal checkerboard)
    # 3 (Black): all 0
    patterns = {
        '.': [
            [255, 255],
            [255, 255]
        ],
        '-': [
            [0, 255],
            [255, 255]
        ],
        '+': [
            [0, 255],
            [255, 0]
        ],
        '#': [
            [0, 0],
            [0, 0]
        ],
        ' ': [  # support spaces inside hood/visor as transparent/white
            [255, 255],
            [255, 255]
        ]
    }

    img = Image.new("1", (64, 64), 255)
    pixels = img.load()

    for y, line in enumerate(sprite_data):
        for x, char in enumerate(line):
            if y < 32 and x < 32:
                # Retrieve the 2x2 dither pattern
                pat = patterns.get(char, patterns['.'])
                # Map one 32x32 sprite pixel to a 2x2 block in the 64x64 output canvas
                pixels[2*x,     2*y]     = pat[0][0]
                pixels[2*x + 1, 2*y]     = pat[0][1]
                pixels[2*x,     2*y + 1] = pat[1][0]
                pixels[2*x + 1, 2*y + 1] = pat[1][1]

    return img
