def get_pixel_art_image(image_id: int) -> Image.Image:
    """
    Generates a 32x32 monochrome PIL Image corresponding to the image_id.
    Defaults to the slime (ID 3) if the image_id is not found.
    """
    sprite_data = SPRITES.get(image_id)
    if not sprite_data:
        logger.warning(f"Pixel art ID {image_id} no encontrado. Usando slime (3) por defecto.")
        sprite_data = SPRITES[3]

    # Create a 32x32 image with mode '1' (1-bit pixels, black and white)
    # Background 255 (white)
    img = Image.new("1", (32, 32), 255)
    pixels = img.load()

    for y, row in enumerate(sprite_data):
        for x, char in enumerate(row):
            # Safe boundary check
            if y < 32 and x < 32:
                if char == '#':
                    pixels[x, y] = 0  # Black
                else:
                    pixels[x, y] = 255  # White

    return img
